const topic39Content = `TEMA 39. EXPLORACIÓN ECOGRÁFICA DEL APARATO GENITAL MASCULINO

TESTÍCULO

INTRODUCCIÓN, ANATOMÍA Y FUNCIONES

La ecografía es la técnica de elección para el estudio de la patología escrotal. Aporta gran resolución espacial y alta sensibilidad para identificar lesiones tanto intra como extratesticulares.

ESCROTO

Saco formado por un conjunto de envolturas dividido en dos por un rafe tendinoso. Cada saco (hemiescroto) contiene un testículo con el epidídimo y el cordón espermático.

Las capas que forman la pared del escroto, desde la superficie hasta los planos profundos, son 7:
→ Piel.
→ Músculo dartos.
→ Capa celular subcutánea.
→ Fascia espermática externa.
→ Músculo cremáster.
→ Fascia espermática interna.
→ Túnica vaginal: membrana serosa con dos capas (visceral y parietal) derivadas del proceso vaginal del peritoneo. Entre ellas existe un espacio virtual. Recubre el testículo y el epidídimo por fuera de la albugínea, salvo en la parte posterior, en la unión del testículo y el epidídimo.

CONTENIDO DEL ESCROTO

TESTÍCULO

Glándulas ovaladas y simétricas alojadas en el escroto. Son las gónadas masculinas y su función es la producción de espermatozoides y hormonas sexuales masculinas.

La túnica albugínea es la capa fibrosa que envuelve el testículo. Emite numerosos septos desde su cara interna que convergen en la parte posterior, donde se pliega hacia el interior formando un septo incompleto llamado MEDIASTINO TESTICULAR.

Esta tabicación da lugar a numerosos lobulillos (200-400), con forma de cuña, que contienen los túbulos seminíferos donde se forma el esperma. Los túbulos confluyen en el mediastino testicular formando la RETE TESTIS.

EPIDÍDIMO

Estructura curvada de unos 6-7 cm, situada posterolateralmente al testículo. Se divide en cabeza, cuerpo y cola. Su función es transportar el semen producido en los conductos espermáticos hasta el conducto deferente.

APÉNDICES TESTICULARES

Son restos embrionarios. Los más frecuentes son el apéndice testicular, de morfología ovoidea y situado en la línea que separa el testículo de la cabeza del epidídimo, y el apéndice epididimario, similar al testicular pero pediculado y localizado en la cabeza del epidídimo.

CORDÓN ESPERMÁTICO

Constituido por el conducto deferente, arterias cremastérica, deferencial y testicular, plexo venoso pampiniforme, nervio genitofemoral, vasos linfáticos y nervios de los testículos. Tiene su origen en el anillo inguinal profundo y desciende verticalmente hacia el escroto.

VASCULARIZACIÓN

El escroto y su contenido están irrigados por 3 arterias: cremastérica, testicular (rama de la aorta) y deferencial.

El drenaje venoso se realiza a través del plexo pampiniforme, formado por la unión de pequeñas venas testiculares que ascienden por el cordón espermático como una red que lo envuelve.

TÉCNICA DE EXPLORACIÓN

Lo primero es revisar los estudios previos para realizar una comparativa.

PREPARACIÓN Y POSICIONAMIENTO

→ Decúbito supino, elevando el escroto y colocando el pene sobre el abdomen para separarlo de los testículos.

EQUIPO

→ Sonda lineal de alta frecuencia, ya que son órganos superficiales.
→ Frecuencias recomendadas: 7-14 MHz.
→ En escrotos aumentados de tamaño pueden utilizarse sondas convexas de baja frecuencia o funciones como imagen panorámica.
→ Se recomienda utilizar bastante gel.
→ Doppler color con frecuencias altas para aportar mayor resolución y sensibilidad en la detección de flujos lentos o escasos.

TÉCNICA

Los testículos deben evaluarse en dos planos: longitudinal y transversal. Las imágenes transversales deben obtenerse en la parte superior, media e inferior del testículo. Las longitudinales, en posiciones central, medial y lateral.

Cada testículo debe barrerse en su totalidad para identificar el epidídimo y sus partes. Debe obtenerse un plano transversal que muestre ambos testículos al mismo tiempo para poder compararlos, o utilizar adquisición de imágenes en doble ventana, valorando ecogenicidad, tamaño y estructura de cada testículo.

El epidídimo se valora con el ecógrafo posicionado sobre el eje longitudinal y posterior del testículo.

ECOGENICIDAD Y MEDIDAS

Debe evaluarse comparativamente el espesor de las cubiertas escrotales. El grosor normal de la pared del escroto es de 2-8 mm, dependiendo de la contracción del músculo cremáster.

Los testículos y epidídimos son discretamente hiperecogénicos en el adulto y pueden ser ligeramente hipoecogénicos en la infancia.

Tamaño normal del testículo adulto:
→ Longitud: 3-5 cm.
→ Ancho: 2-4 cm.
→ Diámetro anteroposterior: hasta 3 cm.

Los epidídimos son isoecogénicos o ligeramente hipoecogénicos respecto a los testículos.

→ Cabeza del epidídimo: forma de pirámide, unos 5-12 mm de longitud máxima, en el polo superior.
→ Cuerpo: muy estrecho, 2-4 mm.
→ Cola: próxima al polo inferior, donde se continúa con la parte proximal del conducto deferente.

MEDIASTINUM TESTIS

Se identifica como una banda hiperecogénica de grosor y longitud variable que se extiende en dirección craneocaudal.

RETE TESTIS

Puede identificarse hasta en un 18 % de los pacientes como un área hipoecogénica estratificada adyacente al mediastinum testis.

TÚNICA ALBUGÍNEA Y TÚNICA VAGINAL

La túnica albugínea aparece como una fina línea ecogénica que rodea el testículo. Las dos capas de la túnica vaginal delimitan un espacio virtual.

Puede existir normalmente una pequeña cantidad de líquido entre ambas capas, identificable como una lengüeta anecogénica cerca de la cabeza del epidídimo, que no debe confundirse con un hidrocele.

Los apéndices testiculares suelen ser isoecogénicos con el parénquima testicular y, con menor frecuencia, quísticos. Es más fácil identificarlos cuando existe líquido entre las capas de la túnica vaginal, ya que normalmente están aplastados contra el testículo y se confunden con el parénquima.

VASCULARIZACIÓN

Se analizará mediante Doppler color, espectral y potencia. Debe realizarse en todas las exploraciones, especialmente en el escroto agudo.

Es imprescindible realizar un estudio comparativo obteniendo imágenes con doble ventana, con parámetros Doppler idénticos para ambos testículos y epidídimos.

Debe empezarse por el testículo sano para ajustar los parámetros de escala de grises y Doppler y mantenerlos durante todo el estudio. Si no se obtiene flujo Doppler, se puede optimizar la imagen aumentando la ganancia y disminuyendo la frecuencia de repetición para aumentar la sensibilidad, o utilizar Doppler potencia, manteniendo los mismos parámetros en ambos testículos.

ESTRUCTURAS EXTRATESTICULARES

Debe realizarse una evaluación ecográfica de las estructuras extratesticulares. Se pueden emplear maniobras de Valsalva.

El cordón espermático es muy superficial y difícil de distinguir de los tejidos blandos que lo rodean. Se localiza superior a la cabeza del epidídimo en plano sagital y puede visualizarse dentro del escroto cuando existe hidrocele o mediante Doppler color.

PATOLOGÍA DEL ESCROTO

ANOMALÍAS CONGÉNITAS

1. TESTÍCULOS NO DESCENDIDOS (CRIPTORQUIDIA): descenso incompleto en su trayecto desde el abdomen al escroto. La bolsa escrotal está vacía. Pueden localizarse en cualquier nivel de la línea de descenso, incluido el canal inguinal.
2. AGENESIA TESTICULAR (ANORQUIA): ausencia de uno o ambos testículos.
3. ATROFIA TESTICULAR: disminución del tamaño testicular respecto a la normalidad.

LESIONES TESTICULARES

1. QUISTE: lesión anecogénica redondeada con refuerzo acústico posterior.
2. QUISTE DE LA TÚNICA: se reconoce porque puede deformar el contorno testicular.
3. ECTASIA DE LA RETE TESTIS: dilatación benigna por obstrucción parcial o completa del conducto deferente. Suele ser bilateral y más frecuente en mayores de 55 años. Se identifica como múltiples estructuras anecogénicas quísticas pequeñas alrededor del mediastino testicular.
4. TUMOR EPIDERMOIDE: lesión redondeada con patrón en “capas de cebolla”, con anillos concéntricos hipo e hiperecogénicos alternantes.
5. MICROLITIASIS TESTICULAR: focos milimétricos hiperecogénicos, sin sombra acústica posterior, distribuidos por el parénquima. La presencia de 5 o más se considera anormal. Se ha relacionado con el desarrollo de tumores germinales testiculares; aunque no hay evidencia de que sea una lesión premaligna, se recomienda seguimiento.
6. MACROCALCIFICACIONES: pueden deberse a procesos cicatriciales.

TUMORES MALIGNOS

Suelen presentarse como una masa hipoecogénica de bordes mal definidos y vascularización interna, aunque los seminomas pueden ser bastante homogéneos. Pueden ser multifocales en los tumores no seminomatosos y presentar áreas quísticas o focos ecogénicos por calcificación, fibrosis o hemorragia.

Se clasifican en:
→ Tumores de células germinales.
→ Tumores no germinales.

ESCROTO AGUDO

Cuadro clínico caracterizado por aparición de dolor agudo acompañado de tumefacción y signos inflamatorios en el escroto. Se considera una urgencia médica.

1. INFLAMACIÓN/INFECCIÓN: EPIDIDIMITIS Y ORQUIEPIDIDIMITIS

Es la causa más frecuente de dolor testicular en adolescentes y adultos. Se caracteriza por inflamación del epidídimo debida a infección.

Características ecográficas:
→ Aumento de flujo en Doppler, habitualmente unilateral.
→ Epidídimo aumentado de tamaño, hipoecogénico o hiperecogénico.
→ Posible hidrocele reactivo.
→ Engrosamiento de las cubiertas escrotales.

Habitualmente comienza afectando a la cola del epidídimo y se extiende al cuerpo y a la cabeza. Si progresa al testículo se produce ORQUIEPIDIDIMITIS: el testículo puede presentar ecogenicidad heterogénea y aumento del flujo Doppler respecto al contralateral.

2. TORSIÓN TESTICULAR

Rotación del testículo sobre sí mismo, de forma que el cordón espermático y sus vasos se retuercen y se produce compromiso vascular. Es una emergencia quirúrgica por el riesgo de isquemia.

Las alteraciones de ecogenicidad suelen aparecer en fases avanzadas, con ecogenicidad heterogénea y áreas hipoecogénicas por congestión, edema e infarto.

Es imprescindible utilizar Doppler. La frecuencia de pulso y el filtro de pared deben estar en niveles bajos. Inicialmente existe ausencia de flujo venoso y posteriormente también arterial en el testículo afectado respecto al contralateral. Debe confirmarse la presencia de flujo en las venas y arterias intratesticulares mediante Doppler pulsado.

En el cordón espermático puede visualizarse el giro o tirabuzón, conocido como WHIRLPOOL SIGN. Es muy específico de torsión y se manifiesta como una masa en espiral posterosuperior al testículo, con ausencia de flujo o flujo escaso en casos de torsión intermitente.

En la resolución espontánea puede observarse un flujo intratesticular muy aumentado por la llamada fase de reperfusión.

3. TORSIÓN DEL APÉNDICE TESTICULAR

El apéndice aparece aumentado de tamaño y con aumento del flujo periférico en Doppler. Es frecuente cierta cantidad de hidrocele reactivo. Después del episodio agudo, el apéndice disminuye de tamaño y se calcifica.

El papel de la ecografía es descartar torsión testicular y orquiepididimitis.

4. TRAUMATISMO

A consecuencia de un traumatismo directo, lo más importante es determinar si existe rotura testicular, ya que es una urgencia quirúrgica.

→ HIDROCELE: colección de líquido anecogénico o con pequeños focos ecogénicos entre las dos capas de la túnica vaginal.
→ HEMATOCELE: colecciones quísticas complejas con septos internos y tabiques que forman compartimentos; su aspecto puede parecerse al del piocele.
→ HEMATOMA: el agudo es hiperecogénico y puede simular una masa testicular; al cabo de unas dos semanas se vuelve quístico.
→ ROTURA TESTICULAR: discontinuidad de la túnica albugínea, posible irregularidad del contorno y ecogenicidad heterogénea con pérdida de vascularización del parénquima.
→ FRACTURA: discontinuidad del parénquima testicular. A veces se identifica una línea hipoecogénica correspondiente a un área avascular, asociada o no a ruptura de la túnica albugínea.

LESIONES EXTRATESTICULARES

1. EPIDÍDIMO
→ QUISTES: frecuentes, habitualmente localizados en la cabeza.
→ ESPERMATOCELE: quistes de retención de esperma, similares a los quistes del epidídimo o con contenido más ecogénico. Se localizan en la cabeza y pueden aparecer después de la vasectomía.
→ TUMOR ADENOMATOIDE: benigno y el más frecuente del epidídimo. Se localiza en la cola y suele ser un nódulo hiperecogénico, homogéneo y de bordes bien definidos. Otros tumores malignos son muy raros.

2. CORDÓN ESPERMÁTICO
→ VARICOCELE: dilatación anormal de las venas del plexo pampiniforme, más frecuente en el lado izquierdo.
Características ecográficas: estructuras anecogénicas serpiginosas en el borde posterosuperior del testículo. El Doppler durante la maniobra de Valsalva es clave. Se observa aumento del diámetro y del flujo de las venas afectadas. En ocasiones es necesario explorar al paciente de pie para potenciar la visualización del aumento del flujo venoso.

3. MISCELÁNEA
→ ESCROTOLITOS (PERLAS ESCROTALES): calcificaciones libres dentro de la túnica vaginal, resultado de torsión de apéndices o depósitos cálcicos inflamatorios. Pueden medir desde unos milímetros hasta 1 cm.
→ HERNIA INGUINOESCROTAL: masa extratesticular más frecuente del saco escrotal. Normalmente contiene asas intestinales o grasa. Las hernias intestinales están llenas de líquido y gas, muestran peristaltismo y aumentan de tamaño con la maniobra de Valsalva. Pueden localizarse en el conducto inguinal o en el escroto.

PRÓSTATA

ANATOMÍA Y FUNCIONES

La próstata es una glándula exocrina con forma de cono invertido. El margen superior es la base y el inferior el ápex. Se localiza en el espacio pélvico, por debajo de la vejiga y rodeando la uretra, por delante del recto, por detrás de la sínfisis púbica y por encima del diafragma urogenital.

Su función como glándula sexual accesoria es producir secreciones que, mezcladas con los espermatozoides en la uretra, constituyen el semen.

Tiene aproximadamente el tamaño de una castaña, con unos 4 cm de diámetro transverso, 3 cm anteroposterior y 3 cm craneocaudal. El peso en jóvenes es de unos 20 g y aumenta con la edad.

La nomenclatura actual utiliza el modelo anatómico de McNeal basado en la anatomía zonal. Se distinguen:
→ GLÁNDULA CENTRAL: zona central fibromuscular anterior y zona transicional.
→ GLÁNDULA PERIFÉRICA.

VESÍCULAS SEMINALES

Son glándulas que producen aproximadamente el 60 % del líquido seminal. Son pares, se localizan superolateralmente a la próstata y están rodeadas por grasa hiperecogénica. Su tamaño y forma varían según la cantidad de contenido. Se reconocen en la pared posterior de la vejiga y miden aproximadamente 3 cm de longitud × 1,5 cm de diámetro.

TÉCNICA DE EXPLORACIÓN ECOGRÁFICA

1. ECOGRAFÍA SUPRAPÚBICA: se utiliza para medir el tamaño de la próstata y el residuo postmiccional. No tiene suficiente resolución para delimitar la anatomía zonal ni para detectar tumores.
2. ECOGRAFÍA TRANSRECTAL: se introduce por el recto un transductor de alta frecuencia con forma cilíndrica. Permite delimitar la anatomía y se utiliza en protocolos de detección del cáncer y procedimientos intervencionistas como guía para biopsias.

PREPARACIÓN DEL PACIENTE

1. ECOGRAFÍA SUPRAPÚBICA: repleción vesical de unos 150 ml. Paciente en decúbito supino, con abdomen y zona suprapélvica descubiertos. Se utiliza sonda convexa o lineal de baja frecuencia, barriendo los ejes transversal y longitudinal para medir sus diámetros. El volumen prostático se calcula mediante el producto de los tres ejes y multiplicando el resultado por 0,523, expresado en mililitros; actualmente lo realiza el ecógrafo.

2. ECOGRAFÍA TRANSRECTAL: paciente en decúbito lateral izquierdo. Enema de limpieza, sonda cubierta con preservativo y abundante gel lubricante. Se obtienen imágenes en plano transversal o semicoronal y sagital.

PATOLOGÍA DE PRÓSTATA Y VESÍCULAS SEMINALES

HIPERTROFIA BENIGNA DE PRÓSTATA

Es la afección más frecuente y suele aparecer a partir de los 50 años. Se caracteriza por sintomatología obstructiva e irritativa de la próstata y del tracto urinario inferior.

Hallazgos ecográficos:
→ Aumento de los diámetros anteroposterior y longitudinal, produciendo una impronta sobre la base vesical.
→ Se considera patológico cuando el volumen es superior a 27 ml o cuando el diámetro anteroposterior supera los 3 cm.
→ Compresión progresiva de la uretra y dificultad para orinar.
→ Dificultad para el flujo de orina desde la vejiga a través de la uretra, con aparición de RESIDUO POSMICCIONAL.
→ Otros hallazgos: nódulos hipoecogénicos o heterogéneos, calcificaciones prostáticas y áreas quísticas.

QUISTES
→ Quistes congénitos (mulleriano y de utrículo).
→ Quistes de retención.
→ Quistes degenerativos.
→ Quistes congénitos de las vesículas seminales, como hallazgo incidental o asociados a otras anomalías genitourinarias.

PROSTATITIS

Proceso inflamatorio agudo o crónico de diversas etiologías. El diagnóstico se basa en el cuadro clínico y la exploración.

Signos ecográficos posibles:
1. Aumento del tamaño prostático.
2. Dolor a la compresión del transductor.
3. Áreas hipoecogénicas, hiperecogénicas o heterogéneas, especialmente en las zonas periféricas.
4. Calcificaciones.
5. Abscesos prostáticos, solo en algunos casos.

PENE

ANATOMÍA Y FUNCIONES

Órgano masculino que participa en los sistemas reproductor y urinario. El interior del pene está constituido por dos cuerpos cavernosos localizados en el dorso y un cuerpo esponjoso de localización ventral que rodea la uretra.

Los tres cuerpos están formados por tejido eréctil, con múltiples sinusoides venosos que se rellenan de sangre durante la erección y están rodeados por una túnica albugínea, fascia de Buck (profunda) y fascia dartos (superficial).

TÉCNICA DE EXPLORACIÓN ECOGRÁFICA E INDICACIONES

La exploración se realiza con el paciente en decúbito supino y el pene en flexión dorsal sobre el abdomen. Debe estudiarse en plano longitudinal y transversal con una sonda lineal de alta frecuencia.

Es importante no ejercer mucha presión con el transductor para no comprimir los vasos. Ecográficamente, los cuerpos cavernosos y el cuerpo esponjoso son estructuras cilíndricas y homogéneas. El cuerpo esponjoso es ligeramente más hipoecogénico que los cuerpos cavernosos.

La túnica albugínea y la fascia de Buck están juntas y se identifican como una sola línea hiperecogénica que rodea los cuerpos cavernosos y el esponjoso.

Las arterias cavernosas, fáciles de identificar con Doppler color, son dos puntos hipoecogénicos localizados en el interior de los cuerpos cavernosos.

Los vasos dorsales (arterias y vena profunda y superficial del pene) se localizan en el dorso del pene, por fuera de la túnica albugínea. Es posible realizar un análisis morfológico y funcional mediante Doppler y mediante la inyección de fármacos vasodilatadores intracavernosos.

INDICACIONES

→ Estudio de disfunción eréctil, tanto de causa arterial como venosa.
→ Induración dolorosa: enfermedad de Peyronie y lesiones focales.
→ Traumatismo: hematoma, rotura y complicaciones.

PUNTOS CLAVE

• La ecografía es la técnica de elección para la patología escrotal.
• El testículo se estudia en planos longitudinal y transversal y siempre de forma comparativa.
• El Doppler es imprescindible en el escroto agudo y especialmente ante sospecha de torsión.
• En la torsión testicular, el whirlpool sign del cordón espermático es muy específico.
• El varicocele se valora especialmente con Doppler y maniobra de Valsalva.
• La ecografía suprapúbica permite medir la próstata y el residuo postmiccional, pero la transrectal delimita mejor la anatomía zonal.
• La hipertrofia benigna de próstata puede producir impronta vesical y residuo postmiccional.
• La ecografía del pene permite valorar anatomía y vascularización, especialmente mediante Doppler.`;

