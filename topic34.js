const topic34Content = `TEMA 34. RADIOLOGÍA CONVENCIONAL. DENSITOMETRÍA

INTRODUCCIÓN:

La osteoporosis consiste en la disminución de la masa ósea y de su resistencia mecánica, que condiciona un aumento de la incidencia de fracturas.

La densitometría es la técnica diagnóstica que permite medir la densidad mineral del hueso.

Hay diferentes zonas de estudio:

⟶ D. de cuerpo entero: obtiene el análisis de la composición corporal determinando el porcentaje de tejido óseo, grasa y partes blandas de todo el organismo y su distribución por regiones.
⟶ D. de columna vertebral
⟶ Valoración de la integración de prótesis de cadera
⟶ Lipodistrofia en pacientes con el virus de la inmunodeficiencia humana.

TIPOS DE DENSITOMETRÍA

Existen diferentes técnicas para medir la densidad mineral ósea basadas en el TC, la ecografía o la RM e isótopos (absorciometría fotónica simple y dual).

Aunque la absorciometría con RX dual o de doble energía DXA es la técnica de elección para cuantificar la masa ósea DMO (densidad mineral ósea), que es el parámetro usado tanto para diagnóstico de osteoporosis como en la monitorización de la respuesta al tratamiento.

Se basa en la diferente absorción de los RX por los distintos componentes del organismo.

ABSORCIOMETRÍA CON RX DE DOBLE ENERGÍA:

1. EQUIPOS

La tecnología varía tanto en hardware (filtros, voltaje) y software (algoritmo) como en la geometría del haz, los equipos consisten en una fuente de RX y un detector de alta resolución. La fuente (tubo de RX) de baja dosis, los equipos de DXA se basan en la energía dual, o sea, producen fotones de dos niveles de energía, existen dos sistemas diferentes para obtener energía dual:

⟶ 1: Emisión alternante de radiación de alto y bajo kilovoltaje
⟶ 2: Un haz monoenergético al que se le añade un filtro de tierras raras para absorber energía separando los fotones de alta y baja energía.

Según la morfología del haz, hay dos tipos de equipos:

HAZ EN LAPICERO ⟶ colimador puntual, se registra con un único detector

HAZ EN ABANICO ⟶ colimador en hendidura, precisa un detector múltiple.

ABSORCIOMETRÍA CON RX DE DOBLE ENERGÍA PORTÁTIL (esqueleto periférico)

Son más pequeños y baratos, pero también menor fiabilidad, sirven como técnica de cribado para seleccionar pacientes que deben someterse a estudio con mesa estable.

El estudio con portátil se hace en la falange media del tercer dedo de la mano no dominante.

ABSORCIOMETRÍA CON RX DE DOBLE ENERGÍA MESA ESTABLE (esqueleto axial)

Es el equipo más usado para el estudio de osteoporosis estudiando las regiones de columna lumbar y cadera.

PROTOCOLOS DE ESTUDIO EN MESA ESTABLE

⟶ Preparación del estudio: los pacientes no requieren una preparación específica, aunque es importante interrogar al paciente para saber:

1. Contraindicaciones: embarazo, contraste oral 5 días antes, estudios de medicina nuclear 2 días antes,
2. Lesiones o enfermedades óseas: fracturas, espondilitis...
3. Debemos retirar todos los objetos metálicos.
4. Antes de empezar el técnico mete todos los datos del paciente en la máquina, en algunos casos la longitud del antebrazo si se va a estudiar ese área.
5. Explicación del estudio y la necesidad de permanecer quieto durante el estudio.

⟶ Regiones de estudio en ADULTOS: el estudio se realiza generalmente en columna lumbar (L1-L4) y fémur proximal, añadiremos el antebrazo en pacientes en los que una de las áreas anteriores no sirva, o en pacientes con hiperparatiroidismo, ya que en ellos el antebrazo se suele afectar de manera precoz.

⟶ Regiones de estudio en NIÑOS y ADOLESCENTES (-20): Sólo se estudia el área lumbar.

COLOCACIÓN DEL PACIENTE Y CENTRAJE

Es muy importante que la posición sea la correcta y estandarizada y siempre igual.

Columna lumbar PA ⟶ Paciente en decúbito en el centro de la mesa, y alineado con su eje, las rodillas flexionadas sobre un soporte para reducir la lordosis y acercar la columna a la mesa. El centraje se hace poniendo la luz del láser en el punto en el que se quiera empezar. La adquisición empieza desde la región inferior L5, hasta D12. Para el estudio de columna lumbar sería unos 5 cm por debajo del ombligo o ligeramente por debajo del nivel de cresta ilíaca.

La imagen debe incluir cranealmente la vértebra D12 y costillas, y en la parte inferior L5 e ilíaco, y la columna estar centrada y recta.

Cadera ⟶ La densitometría de fémur se puede hacer en cualquiera de las dos, pero es útil acostumbrarse a hacer siempre la misma, a no ser que no se pueda por fracturas, etc. Ponemos al paciente en decúbito centrado en la mesa con la pierna en abducción para mantener recto el eje del fémur y en rotación interna de 15-30º. En la imagen adquirida el trocánter menor no debe ser visible, el punto de referencia para el centraje de inicio de la adquisición se sitúa en el centro del muslo, inmediatamente por debajo de la altura de la sínfisis púbica o unos cm por debajo del trocánter mayor.

La imagen debe incluir la cabeza femoral completa y al menos 1 cm por debajo de la región del trocánter menor, hay que tener en cuenta que por la rotación interna el trocánter menor no debe aparecer en la imagen, y la diáfisis debe estar recta.

Antebrazo ⟶ Se estudia el no dominante, el paciente se coloca sentado al lado de la mesa con el antebrazo apoyado y con la mano en pronación y sujeta con unas bandas. El centraje se hace en el centro de la muñeca a la altura de la estiloides cubital.

La imagen debe incluir 2 cm de diáfisis por encima del tercio del antebrazo y parte del carpo, con el eje diafisario recto y centrado.

COLOCACIÓN DEL ÁREA DE ANÁLISIS

El equipo se coloca de forma automática, pero en algunos casos es necesario corregir la situación del área de análisis ROI (región de interés).

Columna lumbar ⟶ La ROI se sitúa en los cuerpos vertebrales L1 a L4, y el valor útil para el estudio es la DMO media de las cuatro vértebras, se deben excluir del análisis las vértebras con fractura o lesión ya que alterarían la media.

Se reconocen por el tamaño menor que la vértebra adyacente, con una densidad mucho mayor, que corresponde a una vértebra más blanca y por tanto con DMO mayor.

Cadera ⟶ El área de análisis se debe situar en el cuello femoral, evitando la rama isquiopubiana. Lo más importante es el fémur tanto el cuello como en su totalidad.

Antebrazo ⟶ La ROI se sitúa en la extremidad distal del radio con la línea de referencia en la estiloides cubital, la región más importante es el radio.

INTERPRETACIÓN DEL ESTUDIO, TERMINOLOGÍA

⟶ Contenido mineral óseo: Cantidad CONCRETA

⟶ Densidad mineral ósea: Cantidad MEDIA de calcio por unidad de área (g/cm2) o volumen (g/cm3) y se calcula dividiendo el contenido mineral óseo por un área o volumen.

⟶ Puntuación T: Sirve para el diagnóstico de osteoporosis en mujeres posmenopáusicas y se usa también en hombres mayores de 50 años. Esta puntuación es el número de desviaciones estándar de diferencia entre el valor de DMO del paciente y la media de una población de referencia adulta joven de la misma raza y sexo.

Los valores son:

1. Normal: puntuación T >-1,0
2. Osteopenia: puntuación T entre -1 y -2,5
3. Osteoporosis: puntuación T <-2,5.

⟶ Puntuación Z: Se usa en niños y adolescentes (hasta los 20 años) y también para mujeres premenopáusicas y hombres -de 50 años. Es el número de desviaciones estándar de diferencia entre el valor DMO del paciente y la media de una población de referencia de la misma raza, sexo y edad. Con puntuación Z inferior a -2, el diagnóstico es “densidad ósea baja para la edad”.

ABSORCIOMETRÍA CON RAYOS X DE DOBLE ENERGÍA AXIAL EJECUTADA CON MESA ESTABLE DE CUERPO ENTERO VALORACIÓN DE COMPOSICIÓN CORPORAL.

1. Colocación del paciente: La mesa suele tener marcado el rectángulo en el que debe estar incluido el paciente, en decúbito supino, centrado en la mesa, con los brazos a los lados del cuerpo sin tocar las piernas y con los pulgares hacia arriba. La línea superior del rectángulo se sitúa por encima de la cabeza y es el punto de centraje de la adquisición, que en este caso es de arriba hacia abajo. ** Si el paciente es obeso, el estudio se realiza sobre medio cuerpo, para ello se deben incluir cuello, cabeza, brazo y pierna de un lado completamente en la mesa, y después el equipo realiza una estimación de todo el cuerpo.

2. Criterios de posición correcta del paciente en la imagen adquirida (colocación del área de análisis): La imagen resultante consiste en dos representaciones del paciente que muestran respectivamente tejidos blandos y hueso. En una imagen correcta, se ve todo el cuerpo del paciente, y en la adquisición de medio cuerpo, todo un lado, cuello y cabeza. La línea que marca la ROI se sitúa de forma automática, dependiendo de cada área anatómica correspondiente.

INTERPRETACIÓN DEL ESTUDIO (TERMINOLOGÍA)

El equipo calcula la composición por regiones anatómicas: masa grasa, masa magra y hueso en todo el organismo y por regiones. También obtiene la distribución de la grasa en regiones predefinidas en el área pélvica:

⟶ Androide (central)

⟶ Ginoide (cadera y muslos)

⟶ La proporción grasa pélvica es la relación entre el porcentaje de grasa de región androide y ginoide.

El índice de masa corporal no distingue grasa de músculo. Los valores de DMO en cuerpo entero sirven para estimar la mineralización, pero no permiten el diagnóstico de osteoporosis (es necesario hacer el estudio de columna y cadera para correlacionar con las curvas de referencia).

CONTROL DE CALIDAD

Para calibrar el equipo y verificar la exactitud y precisión de las medidas, se debe realizar una prueba de control de calidad diario antes de empezar a hacer mediciones a los pacientes. El control se hará como mínimo una vez por semana si el densitómetro no se está usando. Se usa un bloque de calibración fabricado en un material equivalente al tejido con unas cámaras que simulan hueso con contenido mineral óseo conocido.`;

