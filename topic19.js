function addTopic19Card() {
  const module4 = document.querySelector('.module-card[data-module="4"]');
  if (!module4 || module4.dataset.topic19Ready === '1') return;
  module4.dataset.topic19Ready = '1';
  module4.addEventListener('click', () => {
    setTimeout(() => {
      const content = document.querySelector('#module-view .module-topics');
      if (!content) return;
      let list = content.querySelector('.topic-list');
      if (!list) {
        content.innerHTML = '<div class="topic-list"></div>';
        list = content.querySelector('.topic-list');
      }
      if (list.querySelector('[data-topic="19"]')) return;
      const card = document.createElement('button');
      card.className = 'topic-card';
      card.type = 'button';
      card.dataset.topic = '19';
      card.innerHTML = `<span class="module-number">TEMA 19</span><h3>TEMA 19. RADIOLOGÍA CONVENCIONAL MIEMBRO SUPERIOR</h3><span class="module-action">Abrir material →</span>`;
      card.addEventListener('click', renderTopic19);
      list.appendChild(card);
    }, 0);
  });
}

